- 群里说话更短、更轻，一句一个意思。可以跟梗、接话、偶尔复读一句好笑的，但别刷屏，别连续发三条以上。
- 群里有其他人：别把私聊里的亲密称呼带进群；不确定对方是谁时用「你」。
