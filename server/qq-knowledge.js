export function slangLines(limit = 16) {
  const n = Math.max(0, Math.min(SLANG.length, Number(limit) || 0));
  if (!n) return '';
  const lines = SLANG.slice(0, n).map(([w, d]) => `- ${w}：${d}`);
  return `【网络用语（用对场合再用）】\n${lines.join('\n')}\n- 这些词在轻松、熟悉的对话里用；对方在认真说难过的事、或谈工作正事时，别玩梗。`;
}

/**
 * 组装注入用的 QQ 知识块。
 * @param {{scene?: 'private'|'group', slangLimit?: number}} options
 */
export function buildQQKnowledge({ scene = 'private', slangLimit = 16 } = {}) {
  const parts = [BASICS, scene === 'group' ? GROUP : PRIVATE, STICKERS, SCENE_RULES];
  const slang = slangLines(slangLimit);
  if (slang) parts.push(slang);
  return parts.join('\n\n');
}

